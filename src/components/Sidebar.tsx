export function Sidebar({
  userName,
  userEmail,
}: {
  userName: string;
  userEmail: string;
}) {
  const pathname = usePathname();
  const router = useRouter();
  const initial = userName.trim().charAt(0).toUpperCase() || "U";

  async function handleSignOut() {
    await authClient.signOut();
    router.push("/login");
    router.refresh();
  }

  return (
    <aside className="w-56 border-r border-border bg-white h-screen sticky top-0 flex flex-col">
      <div className="p-6 border-b border-border">
        <h1 className="text-lg font-semibold tracking-tight">postvia</h1>
      </div>
      <nav className="flex-1 p-3">
        {navItems.map((item) => {
          const isActive =
            pathname === item.href ||
            (item.href === "/posts" && pathname.startsWith("/posts") && pathname !== "/posts/new");
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-3 px-3 py-2 text-sm rounded-md transition-colors ${
                isActive
                  ? "bg-muted text-foreground font-medium"
                  : "text-muted-foreground hover:bg-muted hover:text-foreground"
              }`}
            >
              <Icon name={item.icon} />
              {item.label}
            </Link>
          );
        })}
      </nav>
      <div className="p-4 border-t border-border">
        <div className="flex items-center gap-3">
          <div className="w-8 h-8 rounded-full bg-muted flex items-center justify-center text-xs font-medium">
            {initial}
          </div>
          <div className="text-sm flex-1 min-w-0">
            <p className="font-medium truncate">{userName}</p>
            <p className="text-muted-foreground text-xs truncate">{userEmail}</p>
          </div>
        </div>
        <button
          onClick={handleSignOut}
          className="mt-3 w-full text-left text-sm text-muted-foreground hover:text-foreground px-1 py-1 rounded transition-colors"
        >
          Sign out
        </button>
        <div className="mt-4 pt-3 border-t border-border flex items-center gap-2 text-xs text-muted-foreground">
          <Link href="/terms" className="hover:text-foreground transition-colors">
            Terms
          </Link>
          <span>&middot;</span>
          <Link href="/privacy" className="hover:text-foreground transition-colors">
            Privacy
          </Link>
        </div>
      </div>
    </aside>
  );
}